-- Les pseudos donnés, en identifiants, à condition que ce soient tous des
-- associés du joueur courant.
create function enquete_ids_associes(p_pseudos text[])
returns uuid[]
language plpgsql stable security definer set search_path = public
as $$
declare
  v_ids uuid[];
  v_pseudo text;
  v_id uuid;
begin
  v_ids := '{}';
  foreach v_pseudo in array coalesce(p_pseudos, '{}') loop
    v_id := enquete_id_pseudo(v_pseudo);
    if v_id is null or v_id not in (select enquete_associes_de(auth.uid())) then
      raise exception '% n''est pas ton associé.', v_pseudo;
    end if;
    if not (v_id = any (v_ids)) then
      v_ids := v_ids || v_id;
    end if;
  end loop;
  return v_ids;
end;
$$;

-- Les affaires que ni moi ni ces associés n'avons lues, pour préparer un
-- rendez-vous.
create function enquete_dossiers_possibles(p_pseudos text[])
returns jsonb
language plpgsql security definer set search_path = public
as $$
declare
  v_tous uuid[];
begin
  perform enquete_exiger_joueur();
  v_tous := enquete_ids_associes(p_pseudos) || auth.uid();
  return coalesce((
    select jsonb_agg(jsonb_build_object('id', a.id, 'titre', a.titre, 'cadre', a.public -> 'cadre') order by a.id)
    from enquete_affaires a
    where not enquete_deja_lue(a.id, v_tous)
  ), '[]'::jsonb);
end;
$$;

-- Ouvre un rendez-vous : l'hôte est assis, les associés sont attendus.
-- p_affaire null = enveloppe cachetée.
create function enquete_preparer(p_pseudos text[], p_affaire bigint)
returns bigint
language plpgsql security definer set search_path = public
as $$
declare
  v_invites uuid[];
  v_partie bigint;
begin
  perform enquete_exiger_joueur();
  v_invites := enquete_ids_associes(p_pseudos);
  if coalesce(array_length(v_invites, 1), 0) = 0 then
    raise exception 'Choisis au moins un associé.';
  end if;
  if array_length(v_invites, 1) > 5 then
    raise exception 'Six privés au plus autour du bureau.';
  end if;
  if p_affaire is not null and enquete_deja_lue(p_affaire, v_invites || auth.uid()) then
    raise exception 'Quelqu''un a déjà lu ce dossier.';
  end if;
  if not exists (select 1 from enquete_affaires a where not enquete_deja_lue(a.id, v_invites || auth.uid())) then
    raise exception 'Plus aucun dossier que personne n''a lu.';
  end if;

  insert into enquete_parties (affaire_id, mode, cree_par)
  values (p_affaire, 'groupe', auth.uid())
  returning id into v_partie;

  insert into enquete_participants (partie_id, user_id, statut) values (v_partie, auth.uid(), 'present');
  insert into enquete_participants (partie_id, user_id, statut)
  select v_partie, unnest(v_invites), 'invite';

  return v_partie;
end;
$$;

-- Revanche : nouveau rendez-vous avec ceux de cette partie qui sont mes
-- associés.
create function enquete_revanche(p_partie bigint)
returns bigint
language plpgsql security definer set search_path = public
as $$
begin
  if not exists (select 1 from enquete_participants where partie_id = p_partie and user_id = auth.uid()) then
    raise exception 'Partie introuvable.';
  end if;
  return enquete_preparer((
    select array_agg(j.pseudo)
    from enquete_participants pa
    join enquete_joueurs j on j.user_id = pa.user_id
    where pa.partie_id = p_partie and pa.user_id in (select enquete_associes_de(auth.uid()))
  ), null);
end;
$$;

-- État du bureau. Ouvrir le rendez-vous, c'est s'y asseoir.
create function enquete_bureau(p_partie bigint)
returns jsonb
language plpgsql security definer set search_path = public
as $$
declare
  v_partie enquete_parties;
  v_hote text;
begin
  perform enquete_exiger_joueur();
  select * into v_partie from enquete_parties where id = p_partie;
  if not found or not exists (
    select 1 from enquete_participants where partie_id = p_partie and user_id = auth.uid()
  ) then
    raise exception 'Ce rendez-vous n''existe plus.';
  end if;

  update enquete_participants set statut = 'present'
  where partie_id = p_partie and user_id = auth.uid() and statut = 'invite' and v_partie.lancee_at is null;

  select pseudo into v_hote from enquete_joueurs where user_id = v_partie.cree_par;

  return jsonb_build_object(
    'id', v_partie.id,
    'hote', v_hote,
    'moi_hote', v_partie.cree_par = auth.uid(),
    'lancee', v_partie.lancee_at is not null,
    'created_at', v_partie.created_at,
    'affaire', (select jsonb_build_object('titre', a.titre, 'cadre', a.public -> 'cadre')
                from enquete_affaires a where a.id = v_partie.affaire_id),
    'participants', (
      select jsonb_agg(jsonb_build_object(
               'pseudo', j.pseudo,
               'statut', pa.statut,
               'hote', pa.user_id = v_partie.cree_par,
               'moi', pa.user_id = auth.uid()
             ) order by pa.user_id <> v_partie.cree_par, pa.statut <> 'present', lower(j.pseudo))
      from enquete_participants pa
      join enquete_joueurs j on j.user_id = pa.user_id
      where pa.partie_id = p_partie
    )
  );
end;
$$;

-- L'hôte appelle un associé de plus.
create function enquete_appeler(p_partie bigint, p_pseudo text)
returns void
language plpgsql security definer set search_path = public
as $$
declare
  v_partie enquete_parties;
  v_id uuid;
begin
  select * into v_partie from enquete_parties where id = p_partie;
  if not found or v_partie.cree_par <> auth.uid() or v_partie.lancee_at is not null then
    raise exception 'Seul l''hôte peut appeler quelqu''un avant l''ouverture.';
  end if;
  v_id := (enquete_ids_associes(array[p_pseudo]))[1];
  if (select count(*) from enquete_participants where partie_id = p_partie and statut <> 'decline') >= 6 then
    raise exception 'Six privés au plus autour du bureau.';
  end if;
  if v_partie.affaire_id is not null and enquete_deja_lue(v_partie.affaire_id, array[v_id]) then
    raise exception '% a déjà lu ce dossier.', p_pseudo;
  end if;
  insert into enquete_participants (partie_id, user_id, statut) values (p_partie, v_id, 'invite')
  on conflict (partie_id, user_id) do update set statut = 'invite', notifie_invitation = false
  where enquete_participants.statut = 'decline';
end;
$$;

-- Un invité décline ; l'hôte qui part annule le rendez-vous.
create function enquete_quitter_bureau(p_partie bigint)
returns void
language plpgsql security definer set search_path = public
as $$
declare
  v_partie enquete_parties;
begin
  select * into v_partie from enquete_parties where id = p_partie;
  if not found or v_partie.lancee_at is not null then
    return;
  end if;
  if v_partie.cree_par = auth.uid() then
    delete from enquete_parties where id = p_partie;
  else
    update enquete_participants set statut = 'decline' where partie_id = p_partie and user_id = auth.uid();
  end if;
end;
$$;

-- L'hôte ouvre le dossier avec ceux qui sont assis.
create function enquete_ouvrir_dossier(p_partie bigint)
returns bigint
language plpgsql security definer set search_path = public
as $$
declare
  v_partie enquete_parties;
  v_presents uuid[];
  v_affaire bigint;
begin
  select * into v_partie from enquete_parties where id = p_partie for update;
  if not found or v_partie.cree_par <> auth.uid() then
    raise exception 'Seul l''hôte peut ouvrir le dossier.';
  end if;
  if v_partie.lancee_at is not null then
    return p_partie;
  end if;

  select array_agg(user_id) into v_presents
  from enquete_participants where partie_id = p_partie and statut = 'present';
  if coalesce(array_length(v_presents, 1), 0) < 2 then
    raise exception 'Il faut au moins un associé assis au bureau.';
  end if;

  v_affaire := v_partie.affaire_id;
  if v_affaire is not null and enquete_deja_lue(v_affaire, v_presents) then
    raise exception 'Quelqu''un au bureau a déjà lu ce dossier.';
  end if;
  if v_affaire is null then
    select a.id into v_affaire from enquete_affaires a
    where not enquete_deja_lue(a.id, v_presents)
    order by random() limit 1;
    if v_affaire is null then
      raise exception 'Plus aucun dossier que personne ici n''a lu.';
    end if;
  end if;

  delete from enquete_participants where partie_id = p_partie and statut <> 'present';
  update enquete_parties set affaire_id = v_affaire, lancee_at = now() where id = p_partie;
  return p_partie;
end;
$$;

