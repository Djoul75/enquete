create function enquete_moi()
returns jsonb
language sql stable security definer set search_path = public
as $$
  select jsonb_build_object(
    'pseudo', (select pseudo from enquete_joueurs where user_id = auth.uid()),
    'admin', coalesce((select admin from enquete_joueurs where user_id = auth.uid()), false)
  );
$$;

create function enquete_pseudo_libre(p_pseudo text)
returns boolean
language sql stable security definer set search_path = public
as $$
  select trim(p_pseudo) ~ '^[A-Za-z0-9_À-ÖØ-öø-ÿ-]{3,16}$'
     and not exists (select 1 from enquete_joueurs where lower(pseudo) = lower(trim(p_pseudo)) and user_id <> auth.uid());
$$;

create function enquete_choisir_pseudo(p_pseudo text)
returns void
language plpgsql security definer set search_path = public
as $$
begin
  if auth.uid() is null then
    raise exception 'Connecte-toi d''abord.';
  end if;
  if enquete_est_joueur() then
    raise exception 'Ton agence a déjà un nom.';
  end if;
  if not (trim(p_pseudo) ~ '^[A-Za-z0-9_À-ÖØ-öø-ÿ-]{3,16}$') then
    raise exception 'De 3 à 16 lettres, chiffres, tirets ou soulignés.';
  end if;
  if enquete_id_pseudo(p_pseudo) is not null then
    raise exception 'Ce nom est déjà sur une autre porte.';
  end if;
  insert into enquete_joueurs (user_id, pseudo) values (auth.uid(), trim(p_pseudo));
end;
$$;

create function enquete_associes()
returns jsonb
language plpgsql security definer set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
begin
  perform enquete_exiger_joueur();
  return jsonb_build_object(
    'amis', coalesce((
      select jsonb_agg(jsonb_build_object(
               'pseudo', j.pseudo,
               'ensemble', s.ensemble,
               'moi_devant', s.moi_devant,
               'lui_devant', s.lui_devant
             ) order by lower(j.pseudo))
      from enquete_associes_de(v_uid) ami(id)
      join enquete_joueurs j on j.user_id = ami.id
      cross join lateral (
        select count(*) as ensemble,
               count(*) filter (where moi.score > lui.score) as moi_devant,
               count(*) filter (where lui.score > moi.score) as lui_devant
        from enquete_parties p
        join enquete_participants moi on moi.partie_id = p.id and moi.user_id = v_uid
        join enquete_participants lui on lui.partie_id = p.id and lui.user_id = ami.id
        where p.revelee_at is not null
      ) s
    ), '[]'::jsonb),
    'recues', coalesce((
      select jsonb_agg(j.pseudo order by f.created_at)
      from enquete_amities f join enquete_joueurs j on j.user_id = f.de
      where f.a = v_uid and f.acceptee_at is null
    ), '[]'::jsonb),
    'envoyees', coalesce((
      select jsonb_agg(j.pseudo order by f.created_at)
      from enquete_amities f join enquete_joueurs j on j.user_id = f.a
      where f.de = v_uid and f.acceptee_at is null
    ), '[]'::jsonb)
  );
end;
$$;

-- Renvoie « demande » (envoyée), « associes » (l'autre m'avait déjà demandé,
-- c'est accepté) ou « deja ».
create function enquete_ajouter_associe(p_pseudo text)
returns text
language plpgsql security definer set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_autre uuid;
begin
  perform enquete_exiger_joueur();
  v_autre := enquete_id_pseudo(p_pseudo);
  if v_autre is null then
    raise exception 'Aucune agence à ce nom.';
  end if;
  if v_autre = v_uid then
    raise exception 'C''est ta propre porte.';
  end if;
  if exists (select 1 from enquete_amities where de = v_uid and a = v_autre)
     or exists (select 1 from enquete_amities where de = v_autre and a = v_uid and acceptee_at is not null) then
    return 'deja';
  end if;
  if exists (select 1 from enquete_amities where de = v_autre and a = v_uid) then
    update enquete_amities set acceptee_at = now() where de = v_autre and a = v_uid;
    return 'associes';
  end if;
  insert into enquete_amities (de, a) values (v_uid, v_autre);
  return 'demande';
end;
$$;

create function enquete_repondre_associe(p_pseudo text, p_oui boolean)
returns void
language plpgsql security definer set search_path = public
as $$
declare
  v_autre uuid := enquete_id_pseudo(p_pseudo);
begin
  perform enquete_exiger_joueur();
  if p_oui then
    update enquete_amities set acceptee_at = now()
    where de = v_autre and a = auth.uid() and acceptee_at is null;
  else
    delete from enquete_amities where de = v_autre and a = auth.uid() and acceptee_at is null;
  end if;
end;
$$;

-- Rompt une association, ou retire une demande envoyée.
create function enquete_retirer_associe(p_pseudo text)
returns void
language plpgsql security definer set search_path = public
as $$
declare
  v_autre uuid := enquete_id_pseudo(p_pseudo);
begin
  perform enquete_exiger_joueur();
  delete from enquete_amities
  where (de = auth.uid() and a = v_autre) or (de = v_autre and a = auth.uid() and acceptee_at is not null);
end;
$$;

